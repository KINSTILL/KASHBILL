'use client';

import { DOC_TYPE_CONFIG } from '@/lib/documents/doc-type-config';
import { resolveBrand, readableOn } from '@/lib/pdf/brand';
import {
  formatCurrency,
  formatAmount,
  currencyLabel,
  formatDateShort,
  type DecimalPlaces,
} from '@/lib/pdf/shared/format';
import type { PdfDocument, PdfFormat } from '@/lib/pdf/types';

const PAYMENT_LABELS: Record<string, { fr: string; en: string }> = {
  CASH: { fr: 'Espèces', en: 'Cash' },
  MOBILE_MONEY: { fr: 'Mobile Money', en: 'Mobile Money' },
  BANK_TRANSFER: { fr: 'Virement bancaire', en: 'Bank transfer' },
  CHECK: { fr: 'Chèque', en: 'Check' },
};

export function DocumentPaperPreview({
  doc,
  format,
}: {
  doc: PdfDocument;
  format: PdfFormat;
}) {
  const config = DOC_TYPE_CONFIG[doc.type];
  const isEn = doc.locale === 'EN';
  const isTicket = format === 'ticket';
  const hidePrices = doc.type === 'BORDEREAU' && doc.payload.total === 0;
  const brand = resolveBrand(doc.company);
  const onPrimary = readableOn(brand.primary);
  const decimals: DecimalPlaces =
    doc.decimalPlaces === 1 || doc.decimalPlaces === 2 ? doc.decimalPlaces : 0;
  const unit = currencyLabel(doc.company.currency, doc.locale);

  const clientBlockLabel =
    doc.type === 'BORDEREAU'
      ? isEn
        ? isTicket
          ? 'Recipient'
          : 'Delivered to'
        : isTicket
        ? 'Destinataire'
        : 'Livré à'
      : doc.type === 'RECU'
      ? isEn
        ? isTicket
          ? 'Payer'
          : 'Received from'
        : isTicket
        ? 'Payeur'
        : 'Reçu de'
      : doc.type === 'FACTURE'
      ? isEn
        ? 'Billed to'
        : 'Facturé à'
      : 'Client';

  const totalQty = doc.payload.lines.reduce((acc, l) => acc + l.quantity, 0);
  const showPayment = Boolean(doc.payload.paymentMethod) && !hidePrices;

  return (
    <div className="flex justify-center rounded-2xl border border-slate-200/80 bg-slate-100/80 p-2.5 sm:p-6">
      <div
        className={`relative w-full overflow-hidden bg-white text-slate-900 shadow-lg ring-1 ring-slate-900/5 transition-all ${
          isTicket
            ? 'max-w-[340px] rounded-xl px-4 py-5 text-xs'
            : 'max-w-[780px] rounded-xl px-5 py-6 sm:px-10 sm:py-10 text-xs sm:text-sm'
        }`}
      >
        {/* Bandeau mode gratuit */}
        {doc.watermarked && !doc.whiteLabel && (
          <div className="-mx-5 -mt-6 mb-4 bg-amber-500 px-3 py-1.5 text-center text-[10px] sm:text-xs font-bold tracking-wider text-white sm:-mx-10 sm:-mt-10 sm:mb-6">
            {isEn
              ? 'FREE MODE · DOCUMENT GENERATED BY MYCASHBILL'
              : 'MODE GRATUIT · DOCUMENT GÉNÉRÉ PAR MYCASHBILL'}
          </div>
        )}

        {/* Filigrane diagonal doux en mode gratuit */}
        {doc.watermarked && !doc.whiteLabel && (
          <div
            aria-hidden="true"
            className="pointer-events-none absolute inset-0 flex items-center justify-center overflow-hidden select-none"
          >
            <span className="-rotate-30 text-center text-2xl sm:text-4xl font-extrabold tracking-widest text-slate-400/15 uppercase">
              {isEn ? 'FREE MODE · MYCASHBILL' : 'MODE GRATUIT · MYCASHBILL'}
            </span>
          </div>
        )}

        {/* Barre supérieure couleur de marque */}
        <div
          className="mb-3 sm:mb-4 h-1.5 w-full rounded-sm"
          style={{ backgroundColor: brand.primary }}
        />

        {/* En-tête Entreprise */}
        <div
          className={`flex items-start gap-3 ${
            isTicket ? 'mb-3 border-b pb-3' : 'mb-5'
          }`}
          style={isTicket ? { borderColor: brand.primary } : undefined}
        >
          {doc.company.logoUrl && (
            <img
              src={doc.company.logoUrl}
              alt=""
              className={`shrink-0 object-contain ${
                isTicket ? 'h-11 w-11' : 'h-14 w-14 sm:h-16 sm:w-16'
              }`}
            />
          )}
          <div className="min-w-0 flex-1">
            <h2
              className={`font-bold leading-snug break-words ${
                isTicket ? 'text-sm' : 'text-base sm:text-xl'
              }`}
              style={{ color: brand.primary }}
            >
              {doc.company.businessName ??
                doc.company.legalName ??
                (isEn ? 'My Business' : 'Mon entreprise')}
            </h2>
            {doc.company.legalForm && (
              <p className="text-[11px] italic text-slate-500">
                {doc.company.legalForm}
              </p>
            )}
            {doc.company.legalAddress && (
              <p className="text-[11px] text-slate-600">{doc.company.legalAddress}</p>
            )}
            {doc.company.city && (
              <p className="text-[11px] text-slate-600">{doc.company.city}</p>
            )}
            <p className="text-[11px] text-slate-600">
              {isEn ? 'Phone' : 'Tél'} : {doc.company.phone}
            </p>
            {doc.company.taxId && (
              <p className="text-[11px] text-slate-600">
                {isEn ? 'Tax ID (NIU)' : 'NIU'} : {doc.company.taxId}
              </p>
            )}
            {doc.company.rccm && (
              <p className="text-[11px] text-slate-600">RCCM : {doc.company.rccm}</p>
            )}
          </div>
        </div>

        {/* Titre du document & Numéro / Date */}
        {isTicket ? (
          <div className="mb-3 text-center">
            <h3
              className="text-base font-extrabold tracking-wide uppercase"
              style={{ color: brand.primary }}
            >
              {isEn ? config.labelEn : config.label}
            </h3>
            <p className="text-[11px] text-slate-500">
              N° {doc.number} · {formatDateShort(doc.createdAt, doc.locale)}
            </p>
          </div>
        ) : (
          <div className="mb-5 flex flex-wrap items-end justify-between gap-2">
            <h3
              className="text-xl sm:text-3xl font-extrabold tracking-tight uppercase"
              style={{ color: brand.primary }}
            >
              {isEn ? config.labelEn : config.label}
            </h3>
            <div className="text-right">
              <p className="text-xs sm:text-sm font-bold text-slate-900">
                N° {doc.number}
              </p>
              <p className="text-[11px] sm:text-xs text-slate-500">
                {formatDateShort(doc.createdAt, doc.locale)}
              </p>
            </div>
          </div>
        )}

        {/* Bloc Client */}
        {doc.client && (
          <div
            className="mb-4 rounded-lg border border-slate-200 bg-slate-50/90 px-3 py-2.5 sm:px-4 sm:py-3"
            style={{
              borderLeftWidth: isTicket ? 3 : 4,
              borderLeftColor: brand.primary,
            }}
          >
            <p className="text-[10px] font-semibold tracking-wider text-slate-500 uppercase">
              {clientBlockLabel}
            </p>
            <p className="mt-0.5 text-xs sm:text-sm font-bold text-slate-900 break-words">
              {doc.client.name}
            </p>
            {doc.client.address && (
              <p className="text-[11px] text-slate-600">{doc.client.address}</p>
            )}
            {doc.client.phone && (
              <p className="text-[11px] text-slate-600">{doc.client.phone}</p>
            )}
            {doc.client.taxId && (
              <p className="mt-0.5 text-[11px] font-semibold text-slate-700">
                {isEn ? 'Tax ID' : 'NIU'} : {doc.client.taxId}
              </p>
            )}
          </div>
        )}

        {/* Métadonnées (Validité, Échéance, Référence, Livraison, Proforma) */}
        <div className="mb-4 space-y-1 text-[11px] sm:text-xs">
          {config.showValidity && doc.payload.validityDays ? (
            <p>
              <span className="font-semibold tracking-wide text-slate-500 uppercase">
                {isEn ? 'Validity:' : 'Validité :'}{' '}
              </span>
              <span className="font-bold text-slate-900">
                {doc.payload.validityDays} {isEn ? 'days' : 'jours'}
              </span>
            </p>
          ) : null}

          {config.showDueDate && doc.payload.dueDate ? (
            <p>
              <span className="font-semibold tracking-wide text-slate-500 uppercase">
                {isEn ? 'Due date:' : 'Échéance :'}{' '}
              </span>
              <span className="font-bold text-slate-900">
                {formatDateShort(new Date(doc.payload.dueDate), doc.locale)}
              </span>
            </p>
          ) : null}

          {config.showReferenceNumber && doc.payload.referenceNumber ? (
            <p>
              <span className="font-semibold tracking-wide text-slate-500 uppercase">
                {isEn ? 'Ref.:' : 'Réf. :'}{' '}
              </span>
              <span className="font-bold text-slate-900">
                {doc.payload.referenceNumber}
              </span>
            </p>
          ) : null}

          {config.showPaymentInfo && doc.payload.paymentMethod ? (
            <p>
              <span className="font-semibold tracking-wide text-slate-500 uppercase">
                {isEn ? 'Payment:' : 'Paiement :'}{' '}
              </span>
              <span className="font-bold text-slate-900">
                {PAYMENT_LABELS[doc.payload.paymentMethod]?.[isEn ? 'en' : 'fr'] ??
                  doc.payload.paymentMethod}
                {doc.payload.paymentReference
                  ? ` — ${doc.payload.paymentReference}`
                  : ''}
              </span>
            </p>
          ) : null}

          {config.showShipmentDetails &&
          (doc.payload.deliveryDate || doc.payload.deliveryAddress) ? (
            <p>
              <span className="font-semibold tracking-wide text-slate-500 uppercase">
                {isEn ? 'Delivery:' : 'Livraison :'}{' '}
              </span>
              <span className="font-bold text-slate-900">
                {doc.payload.deliveryDate
                  ? formatDateShort(new Date(doc.payload.deliveryDate), doc.locale)
                  : ''}
                {doc.payload.deliveryAddress
                  ? ` — ${doc.payload.deliveryAddress}`
                  : ''}
              </span>
            </p>
          ) : null}

          {config.showNonContractual && (
            <div className="mt-1.5 inline-block rounded-full border border-amber-300 bg-amber-50 px-2.5 py-0.5 text-[10px] font-bold text-amber-900">
              {isEn
                ? 'Document without accounting or fiscal value — Proforma Invoice'
                : 'Document sans valeur comptable ou fiscale — Facture Proforma'}
            </div>
          )}
        </div>

        {/* Tableau des articles / lignes */}
        {isTicket ? (
          <div className="mb-3">
            <div
              className="flex items-center justify-between border-y bg-slate-100 px-2 py-1.5 text-[10px] font-bold tracking-wider text-slate-500 uppercase"
              style={{ borderColor: brand.primary }}
            >
              <span>{isEn ? 'Description' : 'Désignation'}</span>
              <span>{hidePrices ? (isEn ? 'Qty' : 'Qté') : `Total (${unit})`}</span>
            </div>
            <div className="divide-y divide-slate-200/80">
              {doc.payload.lines.map((line, i) => (
                <div
                  key={i}
                  className={`px-2 py-2 ${i % 2 === 1 ? 'bg-slate-50/70' : ''}`}
                >
                  <p className="text-xs font-medium text-slate-900 break-words">
                    {line.description}
                  </p>
                  <div className="mt-1 flex items-baseline justify-between gap-2">
                    {hidePrices ? (
                      <span className="ml-auto text-xs font-bold text-slate-900 tabular-nums whitespace-nowrap">
                        {line.quantity}
                      </span>
                    ) : (
                      <>
                        <span className="text-[11px] text-slate-500 tabular-nums whitespace-nowrap">
                          {line.quantity} ×{' '}
                          {formatAmount(line.unitPrice, doc.locale, decimals)}
                        </span>
                        <span className="text-xs font-bold text-slate-900 tabular-nums whitespace-nowrap shrink-0 pl-1">
                          {formatAmount(line.total, doc.locale, decimals)}
                        </span>
                      </>
                    )}
                  </div>
                </div>
              ))}
            </div>
          </div>
        ) : (
          <div className="mb-4 overflow-x-auto">
            {/* Tableau A4 avec largeur minimale garantie sur mobile pour éviter tout chevauchement de chiffres */}
            <div className="min-w-[440px] sm:min-w-0">
              <div
                className="grid grid-cols-12 items-center border-y bg-slate-100 px-2.5 py-2 text-[10px] sm:text-xs font-bold tracking-wider text-slate-500 uppercase"
                style={{ borderColor: brand.primary }}
              >
                <span className={hidePrices ? 'col-span-9' : 'col-span-5 sm:col-span-6'}>
                  {isEn ? 'Description' : 'Désignation'}
                </span>
                <span
                  className={
                    hidePrices
                      ? 'col-span-3 text-right'
                      : 'col-span-2 sm:col-span-1 text-center'
                  }
                >
                  {isEn ? 'Qty' : 'Qté'}
                </span>
                {!hidePrices && (
                  <>
                    <span className="col-span-2 sm:col-span-2 text-right whitespace-nowrap">
                      {isEn ? 'Unit' : 'P.U.'} ({unit})
                    </span>
                    <span className="col-span-3 sm:col-span-3 text-right whitespace-nowrap">
                      Total ({unit})
                    </span>
                  </>
                )}
              </div>
              <div className="divide-y divide-slate-200/80">
                {doc.payload.lines.map((line, i) => (
                  <div
                    key={i}
                    className={`grid grid-cols-12 items-start gap-1 px-2.5 py-2 text-[11px] sm:text-xs ${
                      i % 2 === 1 ? 'bg-slate-50/70' : ''
                    }`}
                  >
                    <span
                      className={`${
                        hidePrices ? 'col-span-9' : 'col-span-5 sm:col-span-6'
                      } pr-2 font-medium text-slate-900 break-words`}
                    >
                      {line.description}
                    </span>
                    <span
                      className={`${
                        hidePrices
                          ? 'col-span-3 text-right font-bold text-slate-900'
                          : 'col-span-2 sm:col-span-1 text-center text-slate-600'
                      } tabular-nums whitespace-nowrap`}
                    >
                      {line.quantity}
                    </span>
                    {!hidePrices && (
                      <>
                        <span className="col-span-2 sm:col-span-2 text-right text-slate-600 tabular-nums whitespace-nowrap">
                          {formatAmount(line.unitPrice, doc.locale, decimals)}
                        </span>
                        <span className="col-span-3 sm:col-span-3 text-right font-bold text-slate-900 tabular-nums whitespace-nowrap">
                          {formatAmount(line.total, doc.locale, decimals)}
                        </span>
                      </>
                    )}
                  </div>
                ))}
              </div>
            </div>
          </div>
        )}

        {/* Bloc Totaux */}
        <div className={`mt-4 flex flex-col ${isTicket ? 'items-stretch' : 'items-end'}`}>
          <div className={isTicket ? 'w-full' : 'w-full sm:w-72'}>
            {!hidePrices && (
              <div className="space-y-1.5 text-xs">
                <div className="flex justify-between items-baseline gap-2 text-slate-600">
                  <span className="min-w-0">{isEn ? 'Subtotal' : 'Sous-total'}</span>
                  <span className="font-medium text-slate-900 tabular-nums shrink-0 whitespace-nowrap">
                    {formatCurrency(
                      doc.payload.subtotal,
                      doc.company.currency,
                      doc.locale,
                      decimals
                    )}
                  </span>
                </div>
                {doc.payload.deliveryFee !== null && doc.payload.deliveryFee > 0 && (
                  <div className="flex justify-between items-baseline gap-2 text-slate-600">
                    <span className="min-w-0">{isEn ? 'Delivery' : 'Livraison'}</span>
                    <span className="font-medium text-slate-900 tabular-nums shrink-0 whitespace-nowrap">
                      {formatCurrency(
                        doc.payload.deliveryFee,
                        doc.company.currency,
                        doc.locale,
                        decimals
                      )}
                    </span>
                  </div>
                )}
                {config.showVat &&
                doc.payload.vatAmount !== null &&
                doc.payload.vatRate !== null ? (
                  <>
                    <div className="flex justify-between items-baseline gap-2 text-slate-600">
                      <span className="min-w-0">{isEn ? 'Total excl. VAT' : 'Total HT'}</span>
                      <span className="font-medium text-slate-900 tabular-nums shrink-0 whitespace-nowrap">
                        {formatCurrency(
                          doc.payload.subtotal + (doc.payload.deliveryFee ?? 0),
                          doc.company.currency,
                          doc.locale,
                          decimals
                        )}
                      </span>
                    </div>
                    <div className="flex justify-between items-baseline gap-2 text-slate-600">
                      <span className="min-w-0">
                        {isEn ? 'VAT' : 'TVA'} ({doc.payload.vatRate}%)
                      </span>
                      <span className="font-medium text-slate-900 tabular-nums shrink-0 whitespace-nowrap">
                        {formatCurrency(
                          doc.payload.vatAmount,
                          doc.company.currency,
                          doc.locale,
                          decimals
                        )}
                      </span>
                    </div>
                  </>
                ) : null}
                {doc.payload.depositAmount !== null && doc.payload.depositAmount > 0 && (
                  <div className="flex justify-between items-baseline gap-2 text-slate-600">
                    <span className="min-w-0">{isEn ? 'Deposit' : 'Acompte'}</span>
                    <span className="font-medium text-slate-900 tabular-nums shrink-0 whitespace-nowrap">
                      -{' '}
                      {formatCurrency(
                        doc.payload.depositAmount,
                        doc.company.currency,
                        doc.locale,
                        decimals
                      )}
                    </span>
                  </div>
                )}
              </div>
            )}

            {/* Encadré Total mis en valeur */}
            <div
              className="mt-2.5 rounded-lg px-3.5 py-2.5 shadow-xs flex items-baseline justify-between gap-2"
              style={{
                backgroundColor: brand.primary,
                borderBottomWidth: 3,
                borderBottomColor: brand.accent,
                color: onPrimary,
              }}
            >
              <p className="text-[10px] sm:text-xs font-bold tracking-wider uppercase opacity-90 min-w-0">
                {hidePrices
                  ? isEn
                    ? 'TOTAL ITEMS DELIVERED'
                    : 'TOTAL COLIS / ARTICLES LIVRÉS'
                  : isEn
                  ? 'NET DUE'
                  : 'NET À PAYER'}
              </p>
              <p
                className={`text-right font-extrabold tabular-nums shrink-0 whitespace-nowrap ${
                  isTicket ? 'text-lg' : 'text-xl sm:text-2xl'
                }`}
              >
                {hidePrices
                  ? totalQty
                  : formatCurrency(
                      doc.payload.total,
                      doc.company.currency,
                      doc.locale,
                      decimals
                    )}
              </p>
            </div>
          </div>
        </div>

        {/* Notes */}
        {doc.payload.notes && !isTicket && (
          <p className="mt-4 text-xs italic text-slate-600">
            Note : {doc.payload.notes}
          </p>
        )}

        {/* Signature / Cachet vendeur */}
        {!isTicket && (doc.company.signatureUrl || doc.company.stampUrl) && (
          <div className="mt-5 flex flex-col items-end">
            <p className="mb-1 text-[11px] text-slate-500">
              {isEn ? 'For' : 'Pour'}{' '}
              {doc.company.businessName ?? doc.company.legalName ?? ''}
            </p>
            <div className="flex items-center gap-3">
              {doc.company.stampUrl && (
                <img
                  src={doc.company.stampUrl}
                  alt=""
                  className="h-16 w-16 object-contain"
                />
              )}
              {doc.company.signatureUrl && (
                <img
                  src={doc.company.signatureUrl}
                  alt=""
                  className="h-12 w-28 object-contain"
                />
              )}
            </div>
          </div>
        )}

        {isTicket && doc.company.showStampOnTicket && doc.company.stampUrl && (
          <div className="mt-3 flex justify-center">
            <img
              src={doc.company.stampUrl}
              alt=""
              className="h-14 w-14 object-contain"
            />
          </div>
        )}

        {/* Signature destinataire (Bordereau) */}
        {!isTicket && config.showRecipientSignature && (
          <div className="mt-6 border-t border-slate-300 pt-2">
            <p className="text-[11px] text-slate-500">
              {isEn
                ? 'Recipient signature and stamp'
                : 'Signature et cachet du destinataire'}
            </p>
            <div className="mt-8 w-44 border-t border-slate-900" />
          </div>
        )}

        {/* Pied de page */}
        <div className="mt-5 border-t border-slate-200 pt-3 text-[10px] text-slate-500 space-y-2">
          {showPayment && (
            <div>
              <p className="font-semibold tracking-wider text-slate-500 uppercase">
                {isEn ? 'Accepted payment:' : 'Paiement accepté :'}
              </p>
              <div className="mt-1 flex flex-wrap gap-1.5">
                <span className="rounded bg-slate-100 px-2 py-0.5 text-[10px] font-bold text-slate-900">
                  {PAYMENT_LABELS[doc.payload.paymentMethod!]?.[isEn ? 'en' : 'fr'] ??
                    doc.payload.paymentMethod}
                </span>
                {doc.payload.paymentOperator && (
                  <span className="rounded bg-orange-100 px-2 py-0.5 text-[10px] font-bold text-orange-700">
                    {doc.payload.paymentOperator}
                  </span>
                )}
                {doc.payload.paymentOperatorFreeText && (
                  <span className="rounded bg-yellow-100 px-2 py-0.5 text-[10px] font-bold text-yellow-800">
                    {doc.payload.paymentOperatorFreeText}
                  </span>
                )}
              </div>
            </div>
          )}

          {doc.qrCodeDataUrl && (
            <div>
              <p className="font-semibold tracking-wider text-slate-500 uppercase">
                {isEn ? 'Verify authenticity:' : "Vérifier l'authenticité :"}
              </p>
              <div className="mt-1 inline-block rounded border border-slate-200 bg-slate-50 p-1">
                <img
                  src={doc.qrCodeDataUrl}
                  alt="QR"
                  className={isTicket ? 'h-11 w-11' : 'h-14 w-14'}
                />
              </div>
            </div>
          )}

          {(doc.cgvText ?? doc.company.cgvText) && (
            <p className="text-slate-500">{doc.cgvText ?? doc.company.cgvText}</p>
          )}

          {!doc.whiteLabel && (
            <p className="text-[9px] text-slate-400">
              {isEn
                ? 'Issued via MyCashBill — Document generated electronically. MyCashBill is a technical tool and cannot be held liable for commercial or tax disputes.'
                : 'Émis via MyCashBill — Document généré électroniquement. MyCashBill est un outil technique et ne saurait être tenu responsable des litiges commerciaux ou fiscaux.'}
            </p>
          )}
        </div>
      </div>
    </div>
  );
}
