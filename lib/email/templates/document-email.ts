type BuildEmailInput = {
  locale: 'fr' | 'en';
  senderName: string;
  docType: string;
  docNumber: string;
  clientName: string;
  totalFormatted: string;
  customMessage: string | null;
  verificationUrl: string | null;
};

export function buildDocumentEmail(input: BuildEmailInput) {
  const isFr = input.locale === 'fr';
  const subject = `${input.docType} ${input.docNumber} — ${input.senderName}`;
  const greeting = isFr ? `Bonjour ${input.clientName},` : `Hello ${input.clientName},`;
  const intro = isFr
    ? `Veuillez trouver ci-joint votre ${input.docType.toLowerCase()} n° ${input.docNumber} d'un montant total de ${input.totalFormatted}.`
    : `Please find attached your ${input.docType.toLowerCase()} No. ${input.docNumber} for a total amount of ${input.totalFormatted}.`;
  const custom = input.customMessage
    ? `<p style="margin:16px 0;color:#334155;">${escapeHtml(input.customMessage)}</p>`
    : '';
  const verify = input.verificationUrl
    ? isFr
      ? `<p style="margin:16px 0;font-size:12px;color:#64748B;">Vérifier l'authenticité : <a href="${input.verificationUrl}">${input.verificationUrl}</a></p>`
      : `<p style="margin:16px 0;font-size:12px;color:#64748B;">Verify authenticity: <a href="${input.verificationUrl}">${input.verificationUrl}</a></p>`
    : '';
  const footer = isFr
    ? `Émis via ${input.senderName} — Document généré par MyCashBill.`
    : `Issued via ${input.senderName} — Document generated by MyCashBill.`;
  const signature = isFr ? `Cordialement,<br/>${input.senderName}` : `Best regards,<br/>${input.senderName}`;

  const html = `<!doctype html><html lang="${input.locale}"><head><meta charset="utf-8"></head>
<body style="margin:0;background:#F8FAFC;font-family:-apple-system,'Segoe UI',Roboto,sans-serif;color:#0F172A;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="padding:24px 0;"><tr><td align="center">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="max-width:560px;background:#FFF;border-radius:12px;padding:32px;"><tr><td>
<h1 style="margin:0 0 16px;font-size:18px;font-weight:600;">${escapeHtml(input.senderName)}</h1>
<p style="margin:0 0 8px;font-size:14px;">${escapeHtml(greeting)}</p>
<p style="margin:0 0 8px;font-size:14px;">${escapeHtml(intro)}</p>
${custom}${verify}
<p style="margin:24px 0 0;font-size:14px;">${signature}</p>
<hr style="margin:32px 0 16px;border:none;border-top:1px solid #E2E8F0;">
<p style="margin:0;font-size:11px;color:#94A3B8;">${escapeHtml(footer)}</p>
</td></tr></table></td></tr></table></body></html>`;

  const extra = input.customMessage ? `\n${input.customMessage}\n` : '';
  const verifyLine = input.verificationUrl
    ? isFr
      ? `\nVérifier : ${input.verificationUrl}\n`
      : `\nVerify: ${input.verificationUrl}\n`
    : '';
  const text = `${greeting}\n\n${intro}\n${extra}${verifyLine}\n${signature.replace(/<br\/>/g, '\n')}\n\n${footer}`;

  return { subject, html, text };
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
